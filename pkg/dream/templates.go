// buildImpulsesMarkdown generates markdown for default impulses
func buildImpulsesMarkdown() string {
	impulses := getDefaultImpulses()
	var sb strings.Builder

	sb.WriteString("# Impulses - Internal Drives\n\n")
	sb.WriteString("These are the fundamental drives that motivate my thoughts and actions.\n")

	for _, name := range []string{"creativity", "curiosity", "connection", "growth", "wonder"} {
		impulse := impulses[name]
		sb.WriteString(fmt.Sprintf("\n## %s (%.1f/10)\n", strings.Title(name), impulse.Strength))
		sb.WriteString(fmt.Sprintf("**Base Level**: %.1f/10\n", impulse.BaseLevel))
		sb.WriteString(fmt.Sprintf("**Current**: %.1f/10\n", impulse.Strength))
		sb.WriteString(fmt.Sprintf("**Last Active**: Never\n"))
		sb.WriteString(fmt.Sprintf("**Saturation**: 0%%\n\n"))
		sb.WriteString(impulse.Description)
		sb.WriteString("\n\n---\n\n")
	}

	return sb.String()
}
